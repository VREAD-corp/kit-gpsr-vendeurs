function categoryBlocks(a, lang) {
  const rule = CATEGORY_RULES[a.category];
  if (!rule) return [];
  const blocks = [{ t: 'h2', text: lang === 'fr' ? 'Règles spécifiques à vérifier pour cette catégorie' : 'Specific rules to check for this category' }];
  if (rule.stop) blocks.push({ t: 'note', text: rule.stop[lang] });
  blocks.push({ t: 'ul', items: rule.pointers[lang] });
  return blocks;
}

